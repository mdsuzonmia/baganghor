    public function run(): void
    {
        $now = date('Y-m-d H:i:s');
        $categoryData = [
            'name' => 'হাইড্রোপনিক্স',
            'slug' => 'hydroponics',
            'description' => 'মাটি ছাড়া চাষ, নিউট্রিয়েন্ট সলিউশন, EC, pH ও হাইড্রোপনিক সিস্টেম নিয়ে নতুনদের সহজ বাংলা গাইড।',
            'status' => 'active',
            'sort_order' => 1,
            'seo_title' => 'হাইড্রোপনিক্স গাইড | Taharat Hydroponics',
            'seo_description' => 'হাইড্রোপনিক্স শুরু করার নিয়ম, গাছের পুষ্টি, Nutrient A-B-C, EC ও pH সম্পর্কে সহজ বাংলা গাইড পড়ুন।',
            'updated_at' => $now,
        ];

        $category = $this->db->table('guide_categories')->where('slug', 'hydroponics')->get()->getRowArray();
        if ($category) {
            $this->db->table('guide_categories')->where('id', $category['id'])->update($categoryData);
            $categoryId = (int) $category['id'];
        } else {
            $this->db->table('guide_categories')->insert($categoryData + ['created_at' => $now]);
            $categoryId = (int) $this->db->insertID();
        }

        foreach ($this->articles() as $index => $article) {
            $faq = $article['faq'];
            unset($article['faq']);
            $article['category_id'] = $categoryId;
            $article['status'] = 'published';
            $article['featured'] = $index === 0 ? 1 : 0;
            $article['published_at'] = $article['published_at'] ?? $now;
            $article['views'] = 0;
            $article['reading_time'] = max(1, (int) ceil(count(preg_split('/\s+/u', trim(strip_tags($article['content'])))) / 200));
            $article['seo_title'] = $article['title'];
            $article['seo_description'] = mb_substr($article['excerpt'], 0, 158);
            $article['updated_at'] = $now;

            $existing = $this->db->table('guides')->where('slug', $article['slug'])->get()->getRowArray();
            if ($existing) {
                // Preserve engagement data while keeping the starter content repeatable.
                unset($article['views']);
                $this->db->table('guides')->where('id', $existing['id'])->update($article);
                $guideId = (int) $existing['id'];
            } else {
                $this->db->table('guides')->insert($article + ['created_at' => $now]);
                $guideId = (int) $this->db->insertID();
            }

            $this->db->table('guide_faqs')->where('guide_id', $guideId)->delete();
            foreach ($faq as $sortOrder => [$question, $answer]) {
                $this->db->table('guide_faqs')->insert([
                    'guide_id' => $guideId,
                    'question' => $question,
                    'answer' => $answer,
                    'sort_order' => $sortOrder,
                ]);
            }
        }
    }

