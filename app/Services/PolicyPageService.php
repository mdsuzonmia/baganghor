    public function all(): array
    {
        return array_replace(self::DEFAULT_CONTENT, (new SettingService())->all('policy_pages'));
    }

    public function get(string $key): ?array
    {
        if (!isset(self::PAGES[$key])) return null;
        return self::PAGES[$key] + ['key' => $key, 'body' => $this->all()[$key]];
    }

    public function save(array $values): void
    {
        (new SettingService())->setMany('policy_pages', $values);
    }
